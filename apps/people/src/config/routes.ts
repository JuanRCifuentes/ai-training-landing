/** Key of a page's share image: its path without slashes at the ends, or "home" for the home page. */
const shareImageKey = (path: string) => path.replace(/^\/+|\/+$/g, '') || 'home';

/** Every internal URL is built here, so a route change touches one file. */
export const routes = {
	home: '/',
	course: (slug: string) => `/courses/${slug}/`,
	legal: (slug: string) => `/legal/${slug}/`,
	profession: (slug: string) => `/professions/${slug}/`,
	/** Anchor of a section on the home page, e.g. section('faq') is "/#faq". */
	section: (id: string) => `/#${id}`,
	shareImageKey,
	/** Share image of the page at `path`, generated by pages/og. */
	shareImage: (path: string) => `/og/${shareImageKey(path)}.png`,
};
